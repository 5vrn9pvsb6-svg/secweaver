  function interpolate(template, params = {}) {
    return String(template).replace(/\{(\w+)\}/g, (_, key) => params[key] ?? "");
  }

  function t(key, params = {}) {
    const dictionary = dictionaries[currentLanguage] || dictionaries.en;
    const fallback = dictionaries.en[key] || key;
    return interpolate(dictionary[key] || fallback, params);
  }

  function setLanguage(language) {
    const normalized = language === "en" ? "en" : "zh";
    localStorage.setItem(STORAGE_KEY, normalized);
    localStorage.setItem(MANUAL_STORAGE_KEY, "1");
    window.location.reload();
  }

  window.SW_I18N = {
    language: currentLanguage,
    t,
    setLanguage,
    toggleLanguage: () => setLanguage(currentLanguage === "zh" ? "en" : "zh"),
  };

